function dailyHours(opens: string, closes: string): OutletHours[] {
  return Array.from({ length: 7 }, (_, day) => ({ day, opens, closes }));
}

interface OutletSeed {
  slug: string;
  name: string;
  address: string;
  locality: string;
  distanceKm: number;
  lat: number;
  lng: number;
  phone: string;
  seatingCapacity: number;
  isOpen?: boolean;
  acceptsBookings?: boolean;
  qrEnabled?: boolean;
  opens?: string;
  closes?: string;
}

function buildOutlets(restaurantSlug: string, restaurantId: string, seeds: OutletSeed[]): Outlet[] {
  const gallery = restaurantImages[restaurantSlug]?.gallery ?? [];

  return seeds.map((seed, index) => ({
    id: `${restaurantId}-outlet-${index + 1}`,
    restaurantId,
    name: seed.name,
    slug: seed.slug,
    address: seed.address,
    location: {
      locality: seed.locality,
      city: "Delhi",
      state: "Delhi",
      distanceKm: seed.distanceKm,
      coordinates: { lat: seed.lat, lng: seed.lng },
    },
    phone: seed.phone,
    isOpen: seed.isOpen ?? true,
    hours: dailyHours(seed.opens ?? "12:00", seed.closes ?? "23:00"),
    seatingCapacity: seed.seatingCapacity,
    acceptsBookings: seed.acceptsBookings ?? true,
    qrEnabled: seed.qrEnabled ?? true,
    image: gallery[index % Math.max(gallery.length, 1)] ?? restaurantImages[restaurantSlug].cover,
  }));
}

