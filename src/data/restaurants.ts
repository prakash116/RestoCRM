export function getRestaurantBySlug(slug: string): Restaurant | undefined {
  return restaurants.find((restaurant) => restaurant.slug === slug);
}

export function getOutlet(restaurantSlug: string, outletSlug: string) {
  const restaurant = getRestaurantBySlug(restaurantSlug);
  if (!restaurant) return undefined;
  const outlet = restaurant.outlets.find((candidate) => candidate.slug === outletSlug);
  if (!outlet) return undefined;
  return { restaurant, outlet };
}

/** Featured first, then by rating. Returns the whole catalogue by default. */
export function getFeaturedRestaurants(limit = restaurants.length): Restaurant[] {
  return [...restaurants]
    .sort((a, b) => Number(b.featured) - Number(a.featured) || b.rating.value - a.rating.value)
    .slice(0, limit);
}

export function getRestaurantsByCuisine(cuisineSlug: string): Restaurant[] {
  return restaurants.filter((restaurant) => restaurant.cuisineSlugs.includes(cuisineSlug));
}

/** Every `/restaurants/[slug]/[outlet]` pair — used to build the sitemap. */
export function getAllOutletPaths(): Array<{ restaurantSlug: string; outletSlug: string }> {
  return restaurants.flatMap((restaurant) =>
    restaurant.outlets.map((outlet) => ({
      restaurantSlug: restaurant.slug,
      outletSlug: outlet.slug,
    })),
  );
}
